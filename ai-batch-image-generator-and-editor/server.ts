import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI } from "@google/genai";
import dotenv from "dotenv";

dotenv.config();

async function startServer() {
  const app = express();
  const PORT = 3000;

  app.use(express.json({ limit: "50mb" }));

  // API Route for image generation
  app.post("/api/generate-image", async (req, res) => {
    try {
      const { prompt, negativePrompt, model, aspectRatio, imageSize } = req.body;
      
      if (!prompt) {
        return res.status(400).json({ error: "Prompt is required" });
      }
      
      const apiKey = process.env.GEMINI_API_KEY;
      if (!apiKey) {
        return res.status(500).json({ 
          error: "GEMINI_API_KEY environment variable is missing on the server. Please check the Secrets panel in AI Studio." 
        });
      }
      
      const ai = new GoogleGenAI({
        apiKey: apiKey,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          }
        }
      });

      console.log(`Generating image. Model: ${model}, Aspect Ratio: ${aspectRatio}, Size: ${imageSize}`);

      let finalAspectRatio = aspectRatio || "1:1";
      let finalImageSize = imageSize;

      if (imageSize === "1920x1080") {
        finalImageSize = "2K";
        finalAspectRatio = "16:9";
      }

      if (model === "imagen-4.0-generate-001") {
        const fullPrompt = negativePrompt ? `${prompt}. Negative prompt: ${negativePrompt}` : prompt;
        
        const response = await ai.models.generateImages({
          model: 'imagen-4.0-generate-001',
          prompt: fullPrompt,
          config: {
            numberOfImages: 1,
            outputMimeType: 'image/jpeg',
            aspectRatio: finalAspectRatio,
          },
        });
        
        if (!response.generatedImages || response.generatedImages.length === 0) {
          throw new Error("No image generated by the model");
        }
        
        const base64Bytes = response.generatedImages[0].image.imageBytes;
        return res.json({ 
          success: true, 
          imageData: `data:image/jpeg;base64,${base64Bytes}`,
          modelUsed: model
        });
      } else {
        const parts: any[] = [{ text: prompt }];
        if (negativePrompt) {
          parts.push({ text: `Avoid in the image: ${negativePrompt}` });
        }
        
        const config: any = {
          imageConfig: {
            aspectRatio: finalAspectRatio,
          }
        };
        
        if (finalImageSize) {
          config.imageConfig.imageSize = finalImageSize;
        }

        const response = await ai.models.generateContent({
          model: model || 'gemini-3.1-flash-image',
          contents: { parts },
          config: config
        });

        if (!response.candidates || response.candidates.length === 0) {
          throw new Error("No candidates returned from the model");
        }

        let base64Data = "";
        let textFeedback = "";

        for (const part of response.candidates[0].content.parts) {
          if (part.inlineData) {
            base64Data = part.inlineData.data;
          } else if (part.text) {
            textFeedback += part.text + " ";
          }
        }

        if (!base64Data) {
          throw new Error(textFeedback || "The model returned text feedback but failed to generate the image data. Your prompt may have triggered safety filters or is unsupported. Please try slightly adjusting your description.");
        }

        return res.json({
          success: true,
          imageData: `data:image/png;base64,${base64Data}`,
          feedback: textFeedback.trim(),
          modelUsed: model
        });
      }
    } catch (error: any) {
      console.error("Image generation error:", error);
      return res.status(500).json({ error: error.message || "Failed to generate image" });
    }
  });

  // Serve static files and integrate Vite in development
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server running on http://localhost:${PORT} under NODE_ENV=${process.env.NODE_ENV || 'development'}`);
  });
}

startServer();
